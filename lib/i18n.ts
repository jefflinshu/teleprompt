export type Translations = (typeof translations)[Locale];

function detectLocale(): Locale {
  if (typeof navigator === "undefined") return "zh";
  const lang = navigator.language || (navigator as { userLanguage?: string }).userLanguage || "";
  return lang.startsWith("zh") ? "zh" : "en";
}

export function getLocale(): Locale {
  return detectLocale();
}

export const t: Translations = translations[detectLocale()];

export function getSpeechLang(): string {
  return detectLocale() === "zh" ? "zh-CN" : "en-US";
}

export function detectSpeechLang(textWindow: string): string {
  const cjk = (textWindow.match(/[\u4e00-\u9fff\u3400-\u4dbf]/g) || []).length;
  const total = textWindow.replace(/\s/g, "").length;
  if (total === 0) return detectLocale() === "zh" ? "zh-CN" : "en-US";
  if (cjk / total > 0.15) return "zh-CN";
  return "en-US";
}
